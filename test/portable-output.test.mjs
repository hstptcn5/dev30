test('PDF is opened synchronously from the export click and JSON is labeled as full data', async () => {
  const source = await readFile(new URL('../public/portable-output.js', import.meta.url), 'utf8');
  assert.match(source, /button\('PDF',[\s\S]*\(\) => openPrintDocument\(getPortable\(\)\)\)/);
  assert.doesNotMatch(source, /openPrintDocument\(await getPortable\(\)\)/);
  assert.match(source, /'Full JSON data'/);
  assert.match(source, /Machine-readable snapshot \+ full evidence/);
});

